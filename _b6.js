var topicState = { q:"", theme:"全部" };

function allTopicThemes(){
  var s = ["全部"];
  TOPICS.forEach(function(t){ if(s.indexOf(t.theme) < 0) s.push(t.theme); });
  return s;
}
function b2Ready(){ return typeof window.b2AddCard === "function"; }

function topicMatch(t){
  if(topicState.theme !== "全部" && t.theme !== topicState.theme) return false;
  var q = (topicState.q || "").trim();
  if(!q) return true;
  var blob = [t.name, t.theme, (t.tags||[]).join(" "), t.bg,
              (t.points||[]).join(" "), (t.quotes||[]).join(" "),
              (t.cases||[]).join(" ")].join(" ");
  return blob.indexOf(q) >= 0;
}

function topicCardHTML(t, idx){
  var tags = (t.tags||[]).map(function(x){ return '<span class="b6-pill">'+esc(x)+'</span>'; }).join("");
  var points = (t.points||[]).map(function(p){
    return '<li class="b6-li">'+esc(p)+'</li>';
  }).join("");
  var quotes = (t.quotes||[]).map(function(qt, qi){
    var btn = b2Ready()
      ? '<button class="b6-mini" onclick="b6AddQuote('+idx+','+qi+')">＋ 加入背诵卡</button>'
      : '<span class="b6-muted b6-nomod">（背诵卡模块未加载）</span>';
    return '<div class="b6-quote"><span class="b6-qmark">“</span><span class="b6-qtext">'+esc(qt)+
           '</span>'+btn+'</div>';
  }).join("");
  var cases = (t.cases||[]).map(function(c){
    return '<div class="b6-case">'+esc(c)+'</div>';
  }).join("");
  var linkTip = t.link
    ? '<span class="b6-link" title="可在素材库检索该母题">🔗 关联素材：'+esc(t.link)+'</span>' : "";

  return '<div class="b6-topic" id="b6t'+idx+'">'+
    '<div class="b6-topic-h">'+
      '<b class="b6-topic-name">'+esc(t.name)+'</b>'+
      '<span class="b6-tag th">'+esc(t.theme)+'</span>'+ tags +
    '</div>'+
    '<div class="b6-sec"><div class="b6-sech b6-bg-h">📌 背景</div><div class="b6-bg">'+esc(t.bg)+'</div></div>'+
    '<div class="b6-sec"><div class="b6-sech b6-pt-h">🎯 核心对策</div><ul class="b6-ul">'+points+'</ul></div>'+
    '<div class="b6-sec"><div class="b6-sech b6-qt-h">💎 金句</div>'+quotes+'</div>'+
    '<div class="b6-sec"><div class="b6-sech b6-ca-h">📎 案例</div>'+cases+'</div>'+
    (linkTip ? '<div class="b6-topic-f">'+linkTip+'</div>' : "")+
  '</div>';
}

function renderTopics(){
  var box = document.getElementById("content");
  if(!box) return;
  var themes = allTopicThemes();
  var list = TOPICS.filter(topicMatch);

  setStats("热点专题库 · 精选 "+TOPICS.length+" 个 2024—2026 热点母题 · 当前命中 "+list.length+
           " 个 · 数据仅存本机、离线可用");
  sideNav("热点专题库", TOPICS.map(function(t, i){
    return { id:"b6t"+i, label:"🔥 "+t.name };
  }));

  var chips = themes.map(function(th){
    var on = th === topicState.theme ? " on" : "";
    return '<span class="b6-chip'+on+'" onclick="b6Filter(\''+esc(th)+'\')">'+esc(th)+'</span>';
  }).join("");

  var h = '<div class="b6-wrap">';
  h += '<h2 class="b6-h2">💡 热点专题库</h2>';
  h += '<div class="b6-note">精选 <b>10</b> 个 2024—2026 年高频考点专题，每个专题含 <b>背景 / 核心对策 / 金句 / 案例</b>，可一键把金句加入「背诵卡」。内容自包含、离线可用，数据不出本机。</div>';
  h += '<div class="b6-toolbar">';
  h += '<input id="b6q" class="b6-search" type="text" placeholder="🔎 搜索关键词（专题 / 对策 / 金句 / 案例）" value="'+esc(topicState.q)+'" oninput="b6Search(this.value)">';
  h += '<div class="b6-chips">'+chips+'</div>';
  h += '</div>';

  if(!list.length){
    h += '<div class="b6-empty">没有匹配的专题，试试更换关键词或点“全部”。</div>';
  }else{
    h += '<div class="b6-grid">';
    list.forEach(function(t){
      var idx = TOPICS.indexOf(t);
      h += topicCardHTML(t, idx);
    });
    h += '</div>';
  }
  h += '</div>';
  box.innerHTML = h;

  var inp = document.getElementById("b6q");
  if(inp && topicState.q){
    inp.focus();
    var v = inp.value; inp.value = ""; inp.value = v;   // 光标移到末尾
  }
}

