function b6Filter(theme){ topicState.theme = theme || "全部"; renderTopics(); }
function b6Search(v){ topicState.q = v || ""; renderTopics(); }
function b6AddQuote(ti, qi){
  var t = TOPICS[ti];
  if(!t){ return; }
  var q = (t.quotes || [])[qi];
  if(!q){ return; }
  if(!b2Ready()){ b6Flash("背诵卡模块未加载，无法加入"); return; }
  try{
    // 兼容 _b2.js 的实际实现：b2AddCard(lib, text, theme, title)（其内部会自行提示）
    window.b2AddCard("金句库", q, t.theme, t.name);
  }catch(e){ b6Flash("加入失败，请检查背诵卡模块"); }
}

