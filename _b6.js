function renderFrames(){
  var box = document.getElementById("content");
  if(!box) return;
  if(frameTab < 0 || frameTab >= FRAMES.length) frameTab = 0;

  setStats("五大题型万能框架卡 · "+FRAMES.length+" 类题型 · 审题 / 结构 / 规范词 / 易错 一卡通 · 离线可用");
  sideNav("题型框架卡", FRAMES.map(function(f, i){
    return { id:"b6frameTop", label:"🧩 "+f.type };
  }));

  var tabs = FRAMES.map(function(f, i){
    var on = i === frameTab ? " on" : "";
    return '<span class="b6-tab'+on+'" onclick="b6Tab('+i+')">'+esc(f.type)+'</span>';
  }).join("");

  var cur = FRAMES[frameTab] || {};
  var h = '<div class="b6-wrap" id="b6frameTop">';
  h += '<h2 class="b6-h2">🧩 五大题型万能框架卡</h2>';
  h += '<div class="b6-note">覆盖申论五大题型：概括归纳 / 综合分析 / 提出对策 / 贯彻执行 / 文章写作。每卡含 <b>审题要点 · 结构模板 · 规范词句式 · 易错提醒 · 一句话口诀</b>，即学即用。</div>';
  h += '<div class="b6-tabs">'+tabs+'</div>';
  h += '<div class="b6-frame-wrap"><div class="b6-frame-title">📄 '+esc(cur.type||"")+'</div>';
  h += frameCardHTML(cur);
  h += '</div>';
  h += '</div>';
  box.innerHTML = h;
}

