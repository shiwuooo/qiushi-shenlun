var STORE_KEY = "shenlun_b6_v1";
function loadStore(){
  try{
    var o = JSON.parse(localStorage.getItem(STORE_KEY));
    return (o && typeof o === "object" && !Array.isArray(o)) ? o : {};
  }catch(e){ return {}; }
}
function saveStore(o){
  try{ localStorage.setItem(STORE_KEY, JSON.stringify(o)); return true; }
  catch(e){ return false; }
}

/* ---------------- 通用工具 ---------------- */
function esc(s){
  if(typeof window.esc === "function" && window.esc !== esc) return window.esc(s);
  var v = (s === null || s === undefined) ? "" : String(s);
  return v.replace(/&/g,"&amp;").replace(/</g,"&lt;").replace(/>/g,"&gt;")
          .replace(/"/g,"&quot;").replace(/'/g,"&#39;");
}
function setStats(t){ var el = document.getElementById("stats"); if(el) el.textContent = t; }
function sideNav(title, items){
  var nav = document.getElementById("nav");
  if(!nav) return;
  var h = "<h3>"+esc(title)+"</h3>";
  (items||[]).forEach(function(it){
    h += '<div class="tlink" onclick="var e=document.getElementById(\''+it.id+'\');if(e)e.scrollIntoView({behavior:\'smooth\'})"><span>'+esc(it.label)+'</span></div>';
  });
  nav.innerHTML = h;
}
function b6Flash(msg){
  var t = document.getElementById("b6Flash");
  if(!t){ t = document.createElement("div"); t.id = "b6Flash"; t.className = "b6-flash"; document.body.appendChild(t); }
  t.textContent = msg;
  t.style.opacity = "1";
  clearTimeout(t._tm);
  t._tm = setTimeout(function(){ t.style.opacity = "0"; }, 1500);
}

